  fun forId(id: String?): Int? = id?.let { byId[it] }

  fun forName(name: String): Int? {
    val key = name.trim().lowercase()
    byTitle[name]?.let { return it }
    idsByName[key]?.let { id -> return byId[id] }
    // fuzzy fallback: a nearby-attraction string like "Cagsawa Ruins"
    // should still match a known place name even with minor wording diffs
    val hit = idsByName.entries.firstOrNull { (n, _) -> key.contains(n) || n.contains(key) }
    return hit?.let { byId[it.value] }
  }

  // Tries the id first (exact, stable match), then falls back to
  // resolving by whatever label text is on hand.
  fun resolve(id: String?, label: String): Int? = forId(id) ?: forName(label)
