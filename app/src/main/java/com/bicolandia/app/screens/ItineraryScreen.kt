private val tripLengths = listOf(1, 3, 5, 7)
private val slotLabels = listOf("MORNING", "AFTERNOON", "EVENING")

// Spreads a day's stops across Morning / Afternoon / Evening
private fun slotLabelFor(stopIndex: Int, stopsPerDay: Int): String =
  slotLabels[minOf(slotLabels.size - 1, stopIndex * slotLabels.size / stopsPerDay)]

private enum class TripInterest(val label: String, val icon: ImageVector, val colorHex: String) {
  NATURE("Nature & Adventure", Icons.Filled.Hiking, "#2E7D32"),
  CULTURE("Culture & Heritage", Icons.Filled.AccountBalance, "#6A1B9A"),
  FOOD("Food & Culinary", Icons.Filled.Restaurant, "#EF6C00"),
  BEACHES("Beaches & Islands", Icons.Filled.BeachAccess, "#0288D1"),
  COMPLETE("Complete Set", Icons.Filled.Apps, "#C24444")
}

private enum class TripPace(val label: String, val stopsPerDay: Int, val desc: String) {
  RELAXED("Relaxed", 2, "2 stops / day"),
  BALANCED("Balanced", 3, "3 stops / day"),
  PACKED("Packed", 4, "4 stops / day")
}

private data class ItineraryStop(val place: PlaceDetail, val slotLabel: String)
private data class DayPlan(val dayNumber: Int, val stops: List<ItineraryStop>)

// "Complete Set" trail: everything in the province, split into Morning / Afternoon / Evening
private data class CompletePart(
  val label: String,
  val destinations: List<ProvinceAttraction>,
  val activities: List<ProvinceActivity>,
  val foods: List<ProvinceFood>,
  val stays: List<Accommodation>
)
private data class CompleteDay(val dayNumber: Int, val parts: List<CompletePart>, val festivals: List<ProvinceFestival>)

private fun <T> pickRotating(list: List<T>, start: Int, count: Int): List<T> {
  if (list.isEmpty()) return emptyList()
  return (0 until minOf(count, list.size)).map { list[(start + it) % list.size] }
}

private fun buildCompletePlan(province: Province, days: Int): List<CompleteDay> {
  val dests = provinceAttractions(province)
  val acts = provinceActivities(province)
  val foods = provinceFoods(province)
  val stays = stayData.values.flatten().filter { it.province.equals(province.name, ignoreCase = true) }
  val festivals = provinceFestivals(province)
  val parts = slotLabels.size
  val slots = days * parts
  return (0 until days).map { d ->
    CompleteDay(
      d + 1,
      (0 until parts).map { p ->
        val k = d * parts + p
        CompletePart(
          label = slotLabels[p],
          // round-robin so every part gets a mix of nature, culture and heritage
          destinations = dests.filterIndexed { i, _ -> i % slots == k },
          activities = pickRotating(acts, k * 2, 2),
          foods = pickRotating(foods, k * 2, 2),
          stays = pickRotating(stays, k, 1)
        )
      },
      festivals
    )
  }
}

@Composable
fun ItineraryPlannerScreen(onBack: () -> Unit, onPlaceClick: (PlaceDetail) -> Unit = {}) {
  var selectedProvince by remember { mutableStateOf(provinces.first()) }
  var selectedInterests by remember { mutableStateOf(setOf(TripInterest.NATURE, TripInterest.CULTURE, TripInterest.FOOD, TripInterest.BEACHES)) }
  var selectedPace by remember { mutableStateOf(TripPace.BALANCED) }
  var selectedDays by remember { mutableStateOf(3) }
  var plan by remember { mutableStateOf<List<DayPlan>>(emptyList()) }
  var completePlan by remember { mutableStateOf<List<CompleteDay>>(emptyList()) }
  val completeMode = TripInterest.COMPLETE in selectedInterests
  var generated by remember { mutableStateOf(false) }

  fun pool(): List<PlaceDetail> {
    val nature = (destinationsData.values.flatten() + activitiesData.values.flatten())
      .filter { it.location.contains(selectedProvince.name) }
    val beaches = nature.filter { it.category.contains("Beach") || it.category.contains("Island") }
    val culture = cultureData.values.flatten()
      .filter { it.location.contains(selectedProvince.name) || it.location.contains("Bicol") || it.location.contains("Region") }
    val food = restaurants.filter { it.location.contains(selectedProvince.name) }

    val combined = mutableListOf<PlaceDetail>()
    if (TripInterest.NATURE in selectedInterests) combined += nature
    if (TripInterest.CULTURE in selectedInterests) combined += culture
    if (TripInterest.FOOD in selectedInterests) combined += food
    if (TripInterest.BEACHES in selectedInterests) combined += beaches
    val result = combined.distinctBy { it.id }
    return result.ifEmpty { nature.ifEmpty { destinationsData.values.flatten() } }
  }

  fun regenerate() {
    if (TripInterest.COMPLETE in selectedInterests) {
      completePlan = buildCompletePlan(selectedProvince, selectedDays)
      plan = emptyList()
      generated = true
      return
    }
    completePlan = emptyList()
    val p = pool()
    if (p.isEmpty()) { plan = emptyList(); generated = true; return }
    var idx = Random.nextInt(p.size)
    plan = (1..selectedDays).map { d ->
      val stops = (0 until selectedPace.stopsPerDay).map { s ->
        val place = p[idx % p.size]; idx++
        ItineraryStop(place, slotLabelFor(s, selectedPace.stopsPerDay))
      }
      DayPlan(d, stops)
    }
    generated = true
  }

  fun swapStop(dayIdx: Int, stopIdx: Int) {
    val p = pool()
    if (p.isEmpty()) return
    val current = plan[dayIdx].stops[stopIdx].place
    val curPos = p.indexOfFirst { it.id == current.id }.let { if (it == -1) 0 else it }
    val next = p[(curPos + 1) % p.size]
    val newStops = plan[dayIdx].stops.toMutableList()
    newStops[stopIdx] = newStops[stopIdx].copy(place = next)
    plan = plan.toMutableList().also { it[dayIdx] = it[dayIdx].copy(stops = newStops) }
  }

  Scaffold(containerColor = BicolBg) { padding ->
    LazyColumn(Modifier.padding(padding)) {
      item { DetailTopBar("Trip Planner", "Your personalized Bicol trail", onBack, trailingIcon = null) }

      item {
        Column(Modifier.padding(horizontal = 16.dp, vertical = 4.dp)) {
          Text("WHERE TO?", color = BicolCoral, fontWeight = FontWeight.Bold, fontSize = 11.sp)
          Spacer(Modifier.height(8.dp))
        }
      }
      item {
        LazyRow(Modifier.padding(horizontal = 16.dp), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
          items(provinces) { p ->
            val selected = p.id == selectedProvince.id
            Box(
              Modifier
                .clip(RoundedCornerShape(16.dp))
                .background(if (selected) Color.fromHex(p.colorHex) else Color.White)
                .clickable { selectedProvince = p; generated = false }
                .padding(horizontal = 16.dp, vertical = 12.dp)
            ) {
              Text(p.name, color = if (selected) Color.White else BicolTextPrimary, fontWeight = FontWeight.SemiBold, fontSize = 13.sp)
            }
          }
        }
      }

      item {
        Column(Modifier.padding(horizontal = 16.dp, vertical = 4.dp)) {
          Spacer(Modifier.height(18.dp))
          Text("WHAT'S YOUR VIBE?", color = BicolCoral, fontWeight = FontWeight.Bold, fontSize = 11.sp)
          Text("Pick as many as you like - this shapes your whole trail.", color = BicolTextSecondary, fontSize = 11.sp)
          Spacer(Modifier.height(8.dp))
        }
      }
      item {
        LazyRow(Modifier.padding(horizontal = 16.dp), horizontalArrangement = Arrangement.spacedBy(10.dp)) {
          items(TripInterest.values().toList()) { interest ->
            val selected = interest in selectedInterests
            val tint = Color.fromHex(interest.colorHex)
            Column(
              Modifier
                .width(108.dp)
                .clip(RoundedCornerShape(16.dp))
                .background(if (selected) tint.copy(alpha = 0.14f) else Color.White)
                .clickable {
                  selectedInterests = when {
                    // Complete Set already covers everything, so it stands on its own
                    interest == TripInterest.COMPLETE ->
                      if (selected) setOf(TripInterest.NATURE, TripInterest.CULTURE, TripInterest.FOOD, TripInterest.BEACHES) else setOf(TripInterest.COMPLETE)
                    TripInterest.COMPLETE in selectedInterests -> setOf(interest)
                    selected -> if (selectedInterests.size > 1) selectedInterests - interest else selectedInterests
                    else -> selectedInterests + interest
                  }
                  generated = false
                }
                .padding(12.dp)
            ) {
              Box(
                Modifier.size(30.dp).clip(CircleShape).background(tint.copy(alpha = if (selected) 0.9f else 0.15f)),
                contentAlignment = Alignment.Center
              ) {
                Icon(interest.icon, contentDescription = null, tint = if (selected) Color.White else tint, modifier = Modifier.size(15.dp))
              }
              Spacer(Modifier.height(8.dp))
              Text(interest.label, fontWeight = FontWeight.SemiBold, fontSize = 11.5.sp, lineHeight = 14.sp)
            }
          }
        }
      }

      item {
        Column(Modifier.padding(horizontal = 16.dp, vertical = 4.dp)) {
          Spacer(Modifier.height(18.dp))
          Text("PACE", color = BicolCoral, fontWeight = FontWeight.Bold, fontSize = 11.sp)
          Spacer(Modifier.height(8.dp))
          Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
            TripPace.values().forEach { pace ->
              val selected = pace == selectedPace
              Column(
                Modifier
                  .weight(1f)
                  .clip(RoundedCornerShape(14.dp))
                  .background(if (selected) BicolDeepGreen else Color.White)
                  .clickable { selectedPace = pace; generated = false }
                  .padding(vertical = 10.dp),
                horizontalAlignment = Alignment.CenterHorizontally
              ) {
                Text(pace.label, color = if (selected) Color.White else BicolTextPrimary, fontWeight = FontWeight.Bold, fontSize = 12.5.sp)
                Text(pace.desc, color = if (selected) Color.White.copy(alpha = 0.8f) else BicolTextSecondary, fontSize = 10.sp)
              }
            }
          }
        }
      }

      item {
        Column(Modifier.padding(horizontal = 16.dp, vertical = 4.dp)) {
          Spacer(Modifier.height(18.dp))
          Text("HOW MANY DAYS?", color = BicolCoral, fontWeight = FontWeight.Bold, fontSize = 11.sp)
          Spacer(Modifier.height(8.dp))
          Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
            tripLengths.forEach { d ->
              val selected = d == selectedDays
              Box(
                Modifier
                  .clip(RoundedCornerShape(16.dp))
                  .background(if (selected) BicolCoral else Color.White)
                  .clickable { selectedDays = d; generated = false }
                  .padding(horizontal = 18.dp, vertical = 12.dp)
              ) {
                Text("$d ${if (d == 1) "Day" else "Days"}", color = if (selected) Color.White else BicolTextPrimary, fontWeight = FontWeight.SemiBold, fontSize = 13.sp)
              }
            }
          }
          Spacer(Modifier.height(18.dp))
          Box(
            Modifier
              .fillMaxWidth()
              .clip(RoundedCornerShape(24.dp))
              .background(Brush.horizontalGradient(listOf(BicolDeepGreen, BicolDeepGreen.copy(alpha = 0.85f))))
              .clickable { regenerate() }
              .padding(vertical = 15.dp),
            contentAlignment = Alignment.Center
          ) {
            Row(verticalAlignment = Alignment.CenterVertically) {
              Icon(Icons.Filled.AutoAwesome, contentDescription = null, tint = Color.White, modifier = Modifier.size(16.dp))
              Spacer(Modifier.width(8.dp))
              Text(if (generated) "Regenerate My Trail" else "Generate My Trail", color = Color.White, fontWeight = FontWeight.Bold, fontSize = 14.sp)
            }
          }
        }
      }

      if (generated) {
        item { Spacer(Modifier.height(22.dp)) }
        item { TripSummaryHero(selectedProvince, selectedDays, selectedPace, if (completeMode) provinceAttractions(selectedProvince).size else plan.sumOf { it.stops.size }, completeMode) }
        item { Spacer(Modifier.height(14.dp)) }
        item { TripEssentialsSection(selectedProvince) }
        item {
          Column(Modifier.padding(horizontal = 16.dp, vertical = 4.dp)) {
            Spacer(Modifier.height(10.dp))
            Text("Day-by-Day Guide", fontWeight = FontWeight.Bold, fontSize = 17.sp, color = BicolTextPrimary)
            Text(
              if (completeMode) "Every destination, activity, dish, stay and festival in ${selectedProvince.name}, split into Morning, Afternoon and Evening."
              else "Tap any stop to see full details. Tap the swap icon to try something else.",
              color = BicolTextSecondary, fontSize = 11.5.sp
            )
          }
        }
        if (completeMode) {
          items(completePlan.size) { dayIdx ->
            CompleteDayCard(completePlan[dayIdx], selectedProvince, onPlaceClick)
          }
        } else {
          items(plan.size) { dayIdx ->
            DayPlanCard(plan[dayIdx], selectedProvince, onPlaceClick, onSwap = { stopIdx -> swapStop(dayIdx, stopIdx) })
          }
        }
      }
      item { Spacer(Modifier.height(120.dp)) }
    }
  }
}

@Composable
private fun TripSummaryHero(province: Province, days: Int, pace: TripPace, totalStops: Int, complete: Boolean = false) {
  val budget = budgetHintFor(province)
  val low = budget.substringAfter("₱").substringBefore("-").replace(",", "").toIntOrNull() ?: 1500
  val high = budget.substringAfter("-").substringBefore("/").replace(",", "").toIntOrNull() ?: 3000
  Card(
    Modifier.fillMaxWidth().padding(horizontal = 16.dp),
    shape = RoundedCornerShape(20.dp),
    elevation = CardDefaults.cardElevation(defaultElevation = 3.dp)
  ) {
    Box(Modifier.background(Brush.horizontalGradient(listOf(Color.fromHex(province.colorHex), Color.fromHex(province.colorHex).copy(alpha = 0.8f))))) {
      // Province photo on the right side of the banner, fading into the card color
      val heroRes = AppImages.forId(province.id)
      if (heroRes != null) {
        Box(Modifier.matchParentSize()) {
          Image(
            painter = painterResource(id = heroRes),
            contentDescription = province.name,
            contentScale = ContentScale.Crop,
            modifier = Modifier.align(Alignment.CenterEnd).fillMaxHeight().fillMaxWidth(0.4f)
          )
          Box(
            Modifier.align(Alignment.CenterEnd).fillMaxHeight().fillMaxWidth(0.4f)
              .background(Brush.horizontalGradient(listOf(Color.fromHex(province.colorHex), Color.Transparent)))
          )
        }
      }
      Column(Modifier.padding(18.dp)) {
        Text("$days-Day ${province.name} Trail", color = Color.White, fontWeight = FontWeight.Bold, fontSize = 19.sp)
        Text(if (complete) "Complete Set · all $totalStops destinations" else "${pace.label} pace · $totalStops stops planned", color = Color.White.copy(alpha = 0.85f), fontSize = 12.5.sp)
        Spacer(Modifier.height(14.dp))
        Row {
          HeroStat(Icons.Filled.Place, "$totalStops", "Stops")
          Spacer(Modifier.width(20.dp))
          HeroStat(Icons.Filled.CalendarMonth, "$days", if (days == 1) "Day" else "Days")
          Spacer(Modifier.width(20.dp))
          HeroStat(Icons.Filled.Payments, "\u20b1${(low * days) / 1000}k-${(high * days) / 1000}k", "Est. Total")
        }
      }
    }
  }
}

