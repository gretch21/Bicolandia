@Composable
private fun CompletePartSection(part: CompletePart, province: Province, onPlaceClick: (PlaceDetail) -> Unit) {
  val icon = when (part.label) {
    "MORNING" -> Icons.Filled.WbSunny
    "AFTERNOON" -> Icons.Filled.WbTwilight
    else -> Icons.Filled.NightsStay
  }
  val title = part.label.lowercase().replaceFirstChar { it.uppercase() }
  Spacer(Modifier.height(14.dp))
  Row(verticalAlignment = Alignment.CenterVertically) {
    Icon(icon, contentDescription = null, tint = BicolDeepGreen, modifier = Modifier.size(18.dp))
    Spacer(Modifier.width(8.dp))
    Text(title, fontWeight = FontWeight.Bold, fontSize = 14.sp, color = BicolDeepGreen)
  }
  Spacer(Modifier.height(6.dp))

  if (part.destinations.isEmpty()) {
    Text("Free time - rest, eat and explore around town.", color = BicolTextSecondary, fontSize = 11.5.sp)
  }
  part.destinations.forEach { dest -> CompleteDestinationBlock(dest, province, onPlaceClick) }

  if (part.activities.isNotEmpty()) {
    PartLabel(Icons.Filled.Hiking, "Activities")
    part.activities.forEach { a -> PartLine("${a.name} - ${a.desc}") }
  }
  if (part.foods.isNotEmpty()) {
    PartLabel(Icons.Filled.Restaurant, "Cuisines to try")
    PartLine(part.foods.joinToString(", ") { it.name })
  }
  if (part.stays.isNotEmpty()) {
    PartLabel(Icons.Filled.Hotel, "Where to stay & rest")
    part.stays.forEach { st -> PartLine("${st.name} (${st.type}) - ${st.location}") }
  }
}

@Composable
private fun PartLabel(icon: ImageVector, text: String) {
  Row(Modifier.padding(top = 8.dp), verticalAlignment = Alignment.CenterVertically) {
    Icon(icon, contentDescription = null, tint = BicolTextSecondary, modifier = Modifier.size(13.dp))
    Spacer(Modifier.width(6.dp))
    Text(text.uppercase(), color = BicolTextSecondary, fontWeight = FontWeight.SemiBold, fontSize = 9.5.sp)
  }
}

@Composable
private fun PartLine(text: String) {
  Text("• $text", color = BicolTextPrimary, fontSize = 11.5.sp, lineHeight = 15.sp, modifier = Modifier.padding(start = 19.dp, top = 2.dp))
}

@Composable
private fun CompleteDestinationBlock(dest: ProvinceAttraction, province: Province, onPlaceClick: (PlaceDetail) -> Unit) {
  // Pass the province along so hubs resolve correctly for places listed only by town (e.g. "Naga City")
  val loc = if (dest.location.contains(province.name, ignoreCase = true)) dest.location else "${dest.location}, ${province.name}"
  val guide = buildTravelGuide(dest.name, loc, dest.category)
  val legs = guide.fromManila + guide.fromHub + guide.localTransport
  val detail = dest.imageId?.let { findPlaceById(it) }
  val resId = AppImages.resolve(dest.imageId, dest.name)
  Column(
    Modifier
      .fillMaxWidth()
      .padding(vertical = 4.dp)
      .clip(RoundedCornerShape(12.dp))
      .background(Color(0xFFF7F8FA))
      .then(if (detail != null) Modifier.clickable { onPlaceClick(detail) } else Modifier)
      .padding(10.dp)
  ) {
    Row(verticalAlignment = Alignment.CenterVertically) {
      Box(Modifier.size(46.dp).clip(RoundedCornerShape(10.dp)).background(Color.fromHex(province.colorHex).copy(alpha = 0.2f)), contentAlignment = Alignment.Center) {
        if (resId != null) {
          Image(painter = painterResource(id = resId), contentDescription = dest.name, contentScale = ContentScale.Crop, modifier = Modifier.fillMaxSize())
        } else {
          Icon(iconFor(dest.category), contentDescription = null, tint = Color.fromHex(province.colorHex), modifier = Modifier.size(18.dp))
        }
      }
      Spacer(Modifier.width(10.dp))
      Column(Modifier.weight(1f)) {
        Text(dest.name, fontWeight = FontWeight.Bold, fontSize = 13.sp)
        Text(dest.category, color = BicolDeepGreen, fontWeight = FontWeight.SemiBold, fontSize = 10.sp)
      }
    }
    Spacer(Modifier.height(4.dp))
    Text(dest.blurb, color = BicolTextSecondary, fontSize = 11.sp, lineHeight = 14.5.sp)
    Spacer(Modifier.height(6.dp))
    Text("HOW TO GET THERE", color = BicolCoral, fontWeight = FontWeight.Bold, fontSize = 9.sp)
    legs.forEachIndexed { i, leg ->
      Row(Modifier.padding(top = 3.dp), verticalAlignment = Alignment.Top) {
        Text("${i + 1}.", color = BicolTextSecondary, fontWeight = FontWeight.SemiBold, fontSize = 10.5.sp, modifier = Modifier.width(16.dp))
        Text("${leg.mode}: ${leg.detail} (${leg.duration})", color = BicolTextSecondary, fontSize = 10.5.sp, lineHeight = 14.sp)
      }
    }
  }
}
