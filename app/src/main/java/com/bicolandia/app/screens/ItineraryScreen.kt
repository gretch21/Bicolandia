private fun budgetHintFor(province: Province): String = when {
  province.rating >= 4.85f -> "\u20b12,500-5,000/day"
  province.rating >= 4.7f -> "\u20b12,000-4,000/day"
  else -> "\u20b11,500-3,000/day"
}

